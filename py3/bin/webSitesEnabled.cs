def _verifyRows() -> list[tuple[str, str, str, str, str]]:
    """(fqdn, url, HTTP status, base or proxy, file) of every FQDN nginx serves."""
    rows = []
    for fqdn, url, site in nginxSites.fqdnUrls(nginxSites.sitesEnabled()):
        served = f"base {site.root}" if site.root else f"proxy {site.proxyPass}" if site.proxyPass else "-"
        rows.append((fqdn, url, nginxSites.httpStatus(url), served, site.file))
    return rows


def _summary(rows) -> str:
    """One line: how many sites answer 2xx/3xx, and which do not."""
    bad = [fqdn for fqdn, _, status, _, _ in rows if not status[:1] in ("2", "3")]
    return f"{len(rows) - len(bad)} of {len(rows)} sites answer" + (f"; not: {' '.join(bad)}" if bad else "")


def _printRows(rows) -> None:
    for fqdn, url, status, served, file in rows:
        print(f"{fqdn:24} {url:36} {status:8} {served}   ({file})")


