nginx has no command that lists its server names. =nginx -T= prints the whole configuration it
loaded, every included file in a section of its own; =bisos.webCap.nginxSites= parses that into the
server blocks, their names, listen lines, file, and what =location /= does (a =root= / =alias= base
directory, or a =proxy_pass= target). After a CBM walk (=sysCbmManage.cs -i fullyMaterialize=),
=verify= is the honest check of the hereWeb leaves, and =browse= opens them as tabs.

- =sitesList= --- the FQDNs (not =_=, wildcards or regex names).
- =verify= --- read-only: FQDN, URL, HTTP status (redirects not followed), base or proxy, file.
- =browse [fqdn ...]= --- open them (default all) as tabs: one =firefox --new-tab= call, else
  =xdg-open= per URL.
- =report= --- =verify=, then =browse=.
- =baseFind fqdn= --- the directory the FQDN is served from; none for a proxied site.

nginx -T runs as root (=sudo -n= when not root).

